<#
    Writes the language keys Galacticraft and PlanetProgression read for this pack's own bodies.

    Galacticraft builds a name out of the registry key rather than using anything handed to it:
    CelestialObject.getTranslationKey() is "<type>.<bodyName>" (measured in its bytecode) and the shown name is that key
    plus ".name". So every body MinespaceCelestialRegistry registers is nameless in every GUI until these lines exist -
    including PlanetProgression's research papers, which are named after the body they research.

    The source is **the generated table the Java itself reads** (MinespacePlanetDimensions.java), not the CSV behind it,
    and that distinction is load-bearing: the CSV leaves the solar system's `Star` column empty (the table is what fills
    in "Sol"), so a generator reading the CSV would invent one system per solar-system row and write keys no body has.
    Reading the same lines the Java compiles is the only way the two sides cannot disagree.

    The keys, by the same rule as MinespaceCelestialRegistry:

        body    ->  planet.<key>.name        (moon.<key>.name when the row orbits a parent)
        system  ->  solarsystem.minespace_<slug of the system key>.name
        star    ->  star.minespace_star_<slug of the system key>.name

    Usage:
        tools\build-celestial-lang.ps1
#>
[CmdletBinding()]
param(
    [string]$Table = (Join-Path $PSScriptRoot '..\src\main\java\com\minespace\unofficial\gtceu\MinespacePlanetDimensions.java'),
    [string]$LangDir = (Join-Path $PSScriptRoot '..\src\main\resources\assets\minespace\lang')
)
$ErrorActionPreference = 'Stop'

function ConvertTo-Slug([string]$Text) {
    $out = New-Object System.Text.StringBuilder
    foreach ($ch in $Text.ToLowerInvariant().ToCharArray()) {
        if (($ch -ge 'a' -and $ch -le 'z') -or ($ch -ge '0' -and $ch -le '9')) {
            [void]$out.Append($ch)
        } elseif ($out.Length -gt 0 -and $out[$out.Length - 1] -ne '_') {
            [void]$out.Append('_')
        }
    }
    return $out.ToString().TrimEnd('_')
}

function ConvertFrom-JavaString([string]$Literal) {
    # The table writes non-ASCII as \uXXXX escapes (the generator emits them), and the language file has to carry the
    # character itself - a lang file full of "\u571f\u661f" is a lang file nobody can read.
    $text = $Literal.Trim('"')
    return [regex]::Replace($text, '\\u([0-9a-fA-F]{4})', {
        param($m) [char][int]("0x" + $m.Groups[1].Value)
    })
}

$pattern = 'new Planet\(\s*(-?\d+),\s*"([^"]*)",\s*"([^"]*)",\s*\d+,\s*\d+,\s*(true|false),\s*(\d+),\s*"([^"]*)",\s*"([^"]*)",\s*[^,]+,\s*"([^"]*)"'

$bodies = New-Object System.Collections.Generic.List[string]
$englishNames = [ordered]@{}
$chineseNames = [ordered]@{}
$rows = 0
foreach ($line in (Get-Content -Encoding UTF8 $Table)) {
    $match = [regex]::Match($line, $pattern)
    if (-not $match.Success) { continue }
    $rows++
    $name = $match.Groups[2].Value
    $nameZh = ConvertFrom-JavaString $match.Groups[3].Value
    $landable = $match.Groups[4].Value
    $key = $match.Groups[6].Value
    $star = $match.Groups[7].Value
    $parent = $match.Groups[8].Value
    $prefix = if ([string]::IsNullOrEmpty($parent)) { 'planet' } else { 'moon' }
    $bodies.Add("$prefix.$key.name=$name|$nameZh")

    $systemKey = if ([string]::IsNullOrEmpty($star)) { $name } else { $star }
    if (-not $englishNames.Contains($systemKey)) {
        $englishNames[$systemKey] = if ([string]::IsNullOrEmpty($star)) { $name } else { $star }
        $chineseNames[$systemKey] = if ([string]::IsNullOrEmpty($star)) { $nameZh } else { $star }
    }
}
if ($rows -eq 0) {
    throw "No rows matched in $Table - the table's line format changed and this script would write nothing."
}

$english = New-Object System.Collections.Generic.List[string]
$chinese = New-Object System.Collections.Generic.List[string]
foreach ($body in $bodies) {
    $key, $names = $body -split '=', 2
    $name, $nameZh = $names -split '\|', 2
    $english.Add("$key=$name")
    $chinese.Add("$key=$nameZh")
}
foreach ($systemKey in $englishNames.Keys) {
    $slug = ConvertTo-Slug $systemKey
    $english.Add("solarsystem.minespace_$slug.name=$($englishNames[$systemKey])")
    $english.Add("star.minespace_star_$slug.name=$($englishNames[$systemKey])")
    $chinese.Add("solarsystem.minespace_$slug.name=$($chineseNames[$systemKey])")
    $chinese.Add("star.minespace_star_$slug.name=$($chineseNames[$systemKey])")
}

$startMarker = '# >>> generated by tools\build-celestial-lang.ps1 - do not edit by hand'
$endMarker = '# <<< generated by tools\build-celestial-lang.ps1'

function Write-LangFile([string]$Path, [string[]]$Generated) {
    $existing = if (Test-Path $Path) { Get-Content -Encoding UTF8 $Path } else { @() }
    $kept = New-Object System.Collections.Generic.List[string]
    $inside = $false
    foreach ($line in $existing) {
        if ($line.StartsWith($startMarker)) { $inside = $true; continue }
        if ($line.StartsWith($endMarker)) { $inside = $false; continue }
        if (-not $inside) { $kept.Add($line) }
    }
    $all = New-Object System.Collections.Generic.List[string]
    $all.AddRange($kept)
    while ($all.Count -gt 0 -and $all[$all.Count - 1].Trim() -eq '') { $all.RemoveAt($all.Count - 1) }
    $all.Add('')
    $all.Add($startMarker)
    $all.AddRange([string[]]$Generated)
    $all.Add($endMarker)
    Set-Content -Path $Path -Value $all -Encoding UTF8
}

Write-LangFile (Join-Path $LangDir 'en_us.lang') $english
Write-LangFile (Join-Path $LangDir 'zh_cn.lang') $chinese

Write-Host ("Wrote {0} English and {1} Chinese lines for {2} bodies and {3} systems" -f `
        $english.Count, $chinese.Count, $rows, $englishNames.Count)
